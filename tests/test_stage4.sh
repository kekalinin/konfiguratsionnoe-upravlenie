# Тестирование команд для Этапа 4
# Проверяет uptime, head, tac и обработку ошибок

# 1. Время работы
uptime

# 2. Переход в папку с файлами
cd home/user/documents
ls

# 3. Чтение первых строк файла (по умолчанию 10)
head report.txt

# 4. Чтение первых 1 строки файла
head -n 1 notes.txt

# 5. Чтение файла снизу вверх
tac report.txt

# 6. Обработка ошибок: файл не найден
head nonexistent.txt

# 7. Обработка ошибок: это папка, а не файл
tac home

# 8. Возврат в корень и завершение
cd /
conf-dump
exit
